//! Renders a [`RuleSet`] into a Lua file for Hyprland's `hl.*` config API.

use std::fmt::Write;

use crate::model::RuleSet;

/// Module name the user `require`s from `hyprland.lua`.
pub const MODULE_NAME: &str = "hyprrules";

pub fn render(rules: &RuleSet) -> String {
    let mut out = String::new();
    out.push_str("-- Generated by hyprrules. Manual changes will be overwritten.\n");
    let _ = writeln!(out, "-- Include it from hyprland.lua with: require(\"{MODULE_NAME}\")");

    if !rules.workspace_rules.is_empty() {
        out.push_str("\n-- Workspaces -> monitors\n");
    }
    for rule in &rules.workspace_rules {
        let _ = write!(
            out,
            "hl.workspace_rule({{ workspace = {}, monitor = {}",
            quote(&rule.workspace),
            quote(&rule.monitor)
        );
        if rule.default {
            out.push_str(", default = true");
        }
        out.push_str(" })\n");
    }

    let enabled: Vec<_> = rules.window_rules.iter().filter(|r| r.enabled).collect();
    if !enabled.is_empty() {
        out.push_str("\n-- Apps -> workspaces\n");
    }
    for rule in enabled {
        let workspace = if rule.silent {
            format!("{} silent", rule.workspace)
        } else {
            rule.workspace.clone()
        };
        let _ = write!(
            out,
            "hl.window_rule({{\n    name      = {},\n    match     = {{ class = {} }},\n    workspace = {},\n}})\n",
            quote(&format!("hyprrules-{}", rule.name)),
            quote(&rule.class),
            quote(&workspace),
        );
    }
    out
}

/// Lua string literal with all special characters escaped.
fn quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c if c.is_control() => {
                // Lua decimal escape; fixed width so a following digit isn't swallowed.
                let _ = write!(out, "\\{:03}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::WindowRule;

    #[test]
    fn renders_discord_on_workspace_two_on_monitor() {
        let mut rules = RuleSet::default();
        rules.add_window_rule(WindowRule::for_class("discord", "2"));
        rules.set_workspace_monitor("2", "DP-2");

        let lua = render(&rules);
        assert!(lua.contains(r#"hl.workspace_rule({ workspace = "2", monitor = "DP-2" })"#));
        assert!(lua.contains(r#"match     = { class = "^(discord)$" },"#));
        assert!(lua.contains(r#"workspace = "2 silent","#));
    }

    #[test]
    fn disabled_rules_are_skipped() {
        let mut rules = RuleSet::default();
        let mut rule = WindowRule::for_class("spotify", "2");
        rule.enabled = false;
        rules.add_window_rule(rule);
        assert!(!render(&rules).contains("spotify"));
    }

    #[test]
    fn regex_backslashes_are_escaped_for_lua() {
        assert_eq!(quote(r"^(org\.app)$"), r#""^(org\\.app)$""#);
        assert_eq!(quote("a\"b"), r#""a\"b""#);
    }
}
